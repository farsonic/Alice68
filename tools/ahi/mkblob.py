"""tools/agaboot/ahi16_blob.h from the built driver and mode file, so that
agaboot carries them and puts them in DEVS: when 16-bit sound is switched on.

    python tools/ahi/mkblob.py           (after tools/ahi/build.sh)

SPDX-License-Identifier: GPL-2.0-only
"""
import os
import zlib

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))


def array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return ("static const unsigned char %s[%d] = {\n" % (name, len(data))) + "\n".join(lines) + "\n};\n"


drv = open(os.path.join(here, "aga-hdmi.audio"), "rb").read()
mode = open(os.path.join(here, "AGA-HDMI"), "rb").read()
crc = lambda b: "%08x" % (zlib.crc32(b) & 0xFFFFFFFF)
out = ("/* Generated by tools/ahi/mkblob.py - do not edit. The AHI driver and its\n"
       "   mode file (tools/ahi: aga-hdmi.c, mkmode.py), carried by agaboot for\n"
       "   16-bit sound (ahi16.c). aga-hdmi.audio %d bytes crc %s, AGA-HDMI %d bytes crc %s. */\n"
       % (len(drv), crc(drv), len(mode), crc(mode)))
out += array("ahi16_driver", drv) + array("ahi16_modefile", mode)
p = os.path.join(root, "tools", "agaboot", "ahi16_blob.h")
open(p, "w", newline="\n").write(out)
print(p, len(drv), crc(drv), len(mode), crc(mode))
