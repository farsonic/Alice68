"""arm/aga_blep_tab.h: the band-limited steps for Paula on HDMI (arm/aga_blep.h).

    python tools/mkblep.py

For each rate HDMI may run at, a lowpass that keeps 0-20 kHz and stops at
max(rate - 20 kHz, rate / 2) - whatever folds back from above that lands
above 20 kHz, out of hearing - as a Kaiser-windowed sinc (80 dB), and its
running integral H: a step through that lowpass. A Paula step at time x
between output samples adds delta * H(k - x) at sample k; the table holds
H - u, what the plain step lacks, for the HALF samples either side, at
P + 1 phases of x (linear between them). Q15.

SPDX-License-Identifier: GPL-2.0-only
"""
import math
import os

RATES = [44100, 48000, 88200, 96000, 176400, 192000]
PASS = 20000.0
ATTEN = 80.0
P = 128                                   # phases; row P closes the interpolation
FINE = 2048                               # integration steps per output sample


def bessel_i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def design(rate):
    stop = max(rate - PASS, rate / 2.0)
    fc = (PASS + stop) / 2.0 / rate                # cycles per output sample
    dw = 2 * math.pi * (stop - PASS) / rate
    taps = math.ceil((ATTEN - 8.0) / (2.285 * dw)) + 1
    half = max(4, (taps + 1) // 2)
    beta = 0.1102 * (ATTEN - 8.7)
    i0b = bessel_i0(beta)

    def h(x):                                  # the windowed sinc, continuous in x
        if abs(x) >= half:
            return 0.0
        s = 2 * fc if x == 0 else math.sin(2 * math.pi * fc * x) / (math.pi * x)
        return s * bessel_i0(beta * math.sqrt(1 - (x / half) ** 2)) / i0b

    # H on a fine grid over [-half, half], by the trapezoid rule, normalised to end at 1
    n = 2 * half * FINE
    xs = [-half + i / FINE for i in range(n + 1)]
    hs = [h(x) for x in xs]
    cum = [0.0]
    for i in range(n):
        cum.append(cum[-1] + (hs[i] + hs[i + 1]) / (2 * FINE))
    total = cum[-1]
    cum = [c / total for c in cum]

    def H(x):
        if x <= -half:
            return 0.0
        if x >= half:
            return 1.0
        f = (x + half) * FINE
        i = int(f)
        if i >= n:
            return 1.0
        w = f - i
        return cum[i] * (1 - w) + cum[i + 1] * w

    rows = []
    for p in range(P + 1):
        row = []
        for j in range(2 * half):
            d = j - half + 1 - p / P
            u = 1.0 if j >= half else 0.0
            row.append(int(round((H(d) - u) * 32768)))
        rows.append(row)
    return half, stop, fc * rate, rows


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "arm", "aga_blep_tab.h")
    lines = ["/* Generated by tools/mkblep.py - do not edit. The band-limited steps for",
             "   Paula on HDMI (aga_blep.h): per rate, H - u at P + 1 phases of the",
             "   step's place between samples, for the HALF samples either side, Q15.",
             "   SPDX-License-Identifier: GPL-2.0-only */",
             "#ifndef AGA_BLEP_TAB_H", "#define AGA_BLEP_TAB_H", "", "#include <stdint.h>", "",
             "#define BLEP_P %d" % P, ""]
    halves = []
    for i, rate in enumerate(RATES):
        half, stop, fc, rows = design(rate)
        halves.append(half)
        lines.append("/* %d Hz: flat to %d Hz, stopped from %d Hz, cut-off %d Hz, %d taps */"
                     % (rate, PASS, stop, fc, 2 * half))
        lines.append("static const int16_t blep_tab%d[%d][%d] = {" % (i, P + 1, 2 * half))
        for row in rows:
            lines.append("    { " + ", ".join(str(v) for v in row) + " },")
        lines.append("};")
        lines.append("")
    lines.append("static const int blep_half[%d] = { %s };" % (len(RATES), ", ".join(map(str, halves))))
    lines.append("static const int16_t *const blep_tabs[%d] = { %s };"
                 % (len(RATES), ", ".join("&blep_tab%d[0][0]" % i for i in range(len(RATES)))))
    lines.append("#define BLEP_HALF_MAX %d" % max(halves))
    lines.append("")
    lines.append("#endif")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print(out, "halves", halves)


if __name__ == "__main__":
    main()
