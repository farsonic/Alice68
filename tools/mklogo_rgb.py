"""Make the AGA-PISTORM boot splash: a colour picture with the version on it.

    python tools/mklogo_rgb.py --version 1.110
    python tools/mklogo_rgb.py --version 1.110 --out x.h --preview x.png

Emu68's own splash images are greyscale run-length art that draw_logo() tints
(that is what `logo=purple` does). Ours is a picture, so it carries its own
colours: it is made small, reduced to a palette and encoded as runs of palette
indices, and draw_logo_rgb() in raspi/start_rpi64.c writes them straight into
the RGB565 framebuffer, blown up by the largest whole number that keeps it
inside three quarters of the screen.

The picture has no version on it. The version goes on last, once the picture
is small and has its palette, in two colours of its own: white letters with a
black edge, in the classic bitmap font. So it stays sharp and readable over
any part of the picture, and a release only has to change --version.

SPDX-License-Identifier: GPL-2.0-only
"""
import argparse
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "package", "art", "splash-src.webp")
OUT = os.path.join(ROOT, "third_party", "Emu68", "include", "logo", "logo_aga_rgb.h")

# 400 x 267 for this 3:2 picture. The kernel scales by whole numbers, so that
# is x3 on a 1080p screen (1200 x 801) and x2 on 720p (800 x 534) - about the
# size the old 459 x 256 splash had. At 459 wide it would be x2 and x1.
WIDTH = 400
# The picture is a photograph, not the old pixel art, and 48 colours banded its
# sky and its blue glow. The last two are the version's white and black.
COLORS = 96
# Where the version goes, in the splash's own pixels: top left, on the dark sky.
VER_AT = (6, 5)
VER_SCALE = 1


def version_masks(text, scale):
    """The version at splash resolution: the letters, and a one-pixel black
    edge around them so they read over the light parts of a picture too."""
    font = ImageFont.load_default_imagefont()
    x0, y0, x1, y1 = font.getbbox(text)
    m = Image.new("L", (x1 - x0 + 2, y1 - y0 + 2), 0)      # room for the edge
    ImageDraw.Draw(m).text((1 - x0, 1 - y0), text, fill=255, font=font)
    letters = np.asarray(m) > 127
    if scale > 1:
        letters = letters.repeat(scale, axis=0).repeat(scale, axis=1)
    edge = np.zeros_like(letters)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            edge |= np.roll(np.roll(letters, dy, axis=0), dx, axis=1)
    return letters, edge & ~letters


def encode(idx):
    """Runs of palette indices: count (1..255), index. A run longer than 255
    is split; the decoder needs no state at all."""
    out = bytearray()
    flat = idx.ravel()
    n = flat.size
    i = 0
    while i < n:
        v = flat[i]
        j = i + 1
        while j < n and flat[j] == v and j - i < 255:
            j += 1
        out.append(j - i)
        out.append(int(v))
        i = j
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True, help="e.g. 1.110")
    ap.add_argument("--image", default=SRC)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--width", type=int, default=WIDTH)
    ap.add_argument("--colors", type=int, default=COLORS, help="3-256, two of them the version's")
    ap.add_argument("--ver-scale", type=int, default=VER_SCALE)
    ap.add_argument("--preview", help="PNG at x3, in the screen's RGB565 colours")
    args = ap.parse_args()
    if not 3 <= args.colors <= 256:
        ap.error("--colors must be 3-256")

    im = Image.open(args.image).convert("RGB")
    h = round(im.height * args.width / im.width)
    small = im.resize((args.width, h), Image.LANCZOS)
    q = small.quantize(colors=args.colors - 2, method=Image.MEDIANCUT, dither=Image.NONE)
    pal = list(q.getpalette()[:(args.colors - 2) * 3])
    pal += [0] * ((args.colors - 2) * 3 - len(pal))           # fewer colours than asked
    pal += [255, 255, 255, 0, 0, 0]
    white, black = args.colors - 2, args.colors - 1
    idx = np.array(q, dtype=np.uint8)

    letters, edge = version_masks("Version %s" % args.version, args.ver_scale)
    x, y = VER_AT
    th, tw = letters.shape
    if x + tw > args.width or y + th > h:
        ap.error("the version does not fit at %s" % (VER_AT,))
    region = idx[y:y + th, x:x + tw]
    region[edge] = black
    region[letters] = white
    data = encode(idx)

    rgb565 = []
    for i in range(args.colors):
        r, g, b = pal[i * 3], pal[i * 3 + 1], pal[i * 3 + 2]
        rgb565.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))

    with open(args.out, "w", newline="\n") as f:
        f.write("/* AGA-PISTORM boot splash, generated by tools/mklogo_rgb.py"
                " - do not edit.\n"
                "   Version %s, %dx%d, %d colours. */\n" % (args.version, args.width, h, args.colors))
        f.write("#define LOGO_AGA_RGB_WIDTH  %d\n" % args.width)
        f.write("#define LOGO_AGA_RGB_HEIGHT %d\n" % h)
        f.write("#define LOGO_AGA_RGB_COLORS %d\n" % args.colors)
        f.write("static const unsigned short logo_aga_rgb_pal[%d] = {\n" % args.colors)
        for i in range(0, args.colors, 8):
            f.write("  " + " ".join("0x%04x," % c for c in rgb565[i:i + 8]) + "\n")
        f.write("};\n")
        f.write("static const unsigned char logo_aga_rgb[] = {\n")
        for i in range(0, len(data), 16):
            f.write("  " + " ".join("0x%02x," % b for b in data[i:i + 16]) + "\n")
        f.write("};\n")
        f.write("#define LOGO_AGA_RGB_LEN %d\n" % len(data))

    print("%s: %dx%d, %d colours, %d runs, %.1f KB"
          % (os.path.relpath(args.out, ROOT), args.width, h, args.colors,
             len(data) // 2, len(data) / 1024))
    if args.preview:
        # what the screen shows: the palette at RGB565 precision, x3 as on 1080p
        p565 = []
        for c in rgb565:
            r, g, b = (c >> 11) & 31, (c >> 5) & 63, c & 31
            p565 += [(r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2)]
        pv = Image.fromarray(idx, "P")
        pv.putpalette(p565)
        pv.convert("RGB").resize((args.width * 3, h * 3), Image.NEAREST).save(args.preview)
        print("preview:", args.preview)


if __name__ == "__main__":
    main()
