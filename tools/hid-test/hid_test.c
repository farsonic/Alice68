static int fails;
#define CHECK(c, ...) do { if (!(c)) { fails++; printf("FAIL %s:%d: ", __FILE__, __LINE__); printf(__VA_ARGS__); printf("\n"); } } while (0)

static void want(const char *what, const struct hid_mouse *m, const uint8_t *rep, int len,
                 int mine, int dx, int dy, int wheel, int pan, unsigned btn)
{
    struct hid_mouse_report r;
    int got = hid_mouse_decode(m, rep, len, &r);
    CHECK(got == mine, "%s: mine %d, want %d", what, got, mine);
    if (!mine) return;
    CHECK(r.dx == dx && r.dy == dy && r.wheel == wheel && r.pan == pan && r.buttons == btn,
          "%s: dx %d dy %d wheel %d pan %d buttons %x, want %d %d %d %d %x",
          what, r.dx, r.dy, r.wheel, r.pan, r.buttons, dx, dy, wheel, pan, btn);
}

