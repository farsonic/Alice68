/* ---- game pads (alice_pad.c) ---------------------------------------------------- */
static void wantpad(const char *what, const struct hid_pad *p, const uint8_t *rep, int len, int id,
                    int mine, unsigned dirs, unsigned btn)
{
    struct pad_state s = { 0xff, 0xffff };
    int got = hid_pad_decode(p, rep, len, id, &s);
    CHECK(got == mine, "%s: mine %d, want %d", what, got, mine);
    if (!mine || !got) return;
    CHECK(s.dirs == dirs && s.buttons == btn, "%s: dirs %x buttons %x, want %x %x", what, s.dirs, s.buttons, dirs, btn);
}
