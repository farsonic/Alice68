static void pads(void)
{
    struct hid_pad p;
    static const uint8_t mouse_only[] = { 0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0xc0 };
    CHECK(!hid_pad_parse(mouse_only, sizeof mouse_only, &p), "a mouse is not a pad");

    CHECK(hid_pad_parse(std_pad, sizeof std_pad, &p) && !p.ids && p.nbtn == 16, "standard pad: %d ids %d buttons %d", p.ok, p.ids, p.nbtn);
    { uint8_t r[] = { 0x00, 0x00, 0x08, 0, 0, 0, 0 }; wantpad("std centred", &p, r, 7, -1, 1, 0, 0); }
    { uint8_t r[] = { 0x01, 0x80, 0x08, 0x81, 0, 0, 0 }; wantpad("std left, buttons 1 and 16", &p, r, 7, -1, 1, L, 0x8001); }
    { uint8_t r[] = { 0x00, 0x00, 0x03, 0, 0, 0, 0 }; wantpad("std hat down-right", &p, r, 7, -1, 1, D | R, 0); }
    { uint8_t r[] = { 0x00, 0x00, 0x08, 30, 0x9c, 0, 0 }; wantpad("std stick a little right, up", &p, r, 7, -1, 1, U, 0); }
    { uint8_t r[] = { 0x00, 0x00, 0x00, 60, 0, 0, 0 }; wantpad("std hat up + stick right", &p, r, 7, -1, 1, U | R, 0); }

    CHECK(hid_pad_parse(xbox, sizeof xbox, &p) && p.ids && p.id == 1 && p.x.size == 16 && !p.x.sgn && p.x.max == 65535 && p.hat.min == 1,
          "xbox: id %d x %d/%d hat %d", p.id, p.x.size, (int)p.x.max, (int)p.hat.min);
    {   /* report 1: X Y Z Rz (16 bits each), brake, accel (2 bytes each), hat|pad, buttons (2 bytes) */
        uint8_t r[16] = { 1, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80, 0, 0, 0, 0, 0x00, 0x00, 0x00 };
        wantpad("xbox centred, hat 0 = null", &p, r, 16, -1, 1, 0, 0);
        r[1] = 0; r[2] = 0; r[13] = 3; r[14] = 0x01 | 0x08; r[15] = 0x40;   /* X min, hat 3 = right, A, button 4 (X), button 15 */
        wantpad("xbox left + hat right, A X 15", &p, r, 16, -1, 1, L | R, 0x4009);
        wantpad("xbox: another report", &p, (const uint8_t[]){ 2, 0, 0 }, 3, -1, 0, 0, 0);
        wantpad("xbox, the ID given apart (BLE)", &p, r + 1, 15, 1, 1, L | R, 0x4009);
        wantpad("xbox, another ID given apart", &p, r + 1, 15, 2, 0, 0, 0);
        r[3] = 0xff; r[4] = 0xff; r[13] = 5;                                /* Y max = down, hat 5 = down */
        wantpad("xbox down", &p, r, 16, -1, 1, L | D, 0x4009);
    }

    CHECK(hid_pad_parse(ds4, sizeof ds4, &p) && p.id == 1 && p.x.max == 255 && p.nbtn == 14, "ds4: id %d x max %d buttons %d", p.id, (int)p.x.max, p.nbtn);
    {   /* 1, X Y Z Rz, hat|buttons 1-4 (Square Cross Circle Triangle), buttons 5-12, 13-14|counter, L2, R2 */
        uint8_t r[] = { 1, 0x80, 0x80, 0x80, 0x80, 0x08, 0x00, 0x00, 0x00, 0x00 };
        wantpad("ds4 centred", &p, r, sizeof r, -1, 1, 0, 0);
        r[5] = 0x20 | 0x06;                                                 /* Cross, hat 6 = left */
        wantpad("ds4 Cross, hat left", &p, r, sizeof r, -1, 1, L, 0x2);
        r[5] = 0x08; r[2] = 0x00; r[7] = 0x01 | 0xfc;                       /* stick up, button 13 + counter bits */
        wantpad("ds4 stick up, button 13 (PS), counter ignored", &p, r, sizeof r, -1, 1, U, 0x1000);
    }

    CHECK(hid_pad_parse(swpro, sizeof swpro, &p) && p.id == 0x3f && p.x.size == 16 && p.y.size == 16, "swpro: id %x", p.id);
    {   uint8_t r[] = { 0x3f, 0x02, 0x00, 0x08, 0xff, 0xff, 0x00, 0x80, 0, 0x80, 0, 0x80 };   /* button 2, hat null, X max */
        wantpad("switch pro right, button 2", &p, r, sizeof r, -1, 1, R, 0x2);
        r[3] = 0x07;                                                        /* hat up-left */
        wantpad("switch pro hat up-left + stick right", &p, r, sizeof r, -1, 1, U | L | R, 0x2);
    }

    CHECK(hid_pad_parse(stick, sizeof stick, &p) && !p.ids && p.x.size == 10 && p.hat.max == 3, "joystick: x %d hat %d", p.x.size, (int)p.hat.max);
    {   /* X 10 bits, Y 10 bits, 4 padding, 4 buttons, hat 4 bits: 32 bits */
        uint32_t w = 1023u | (512u << 10) | (0x5u << 24) | (2u << 28);   /* X max, Y centre, buttons 1 and 3, hat 2 = down */
        uint8_t r[4] = { (uint8_t)w, (uint8_t)(w >> 8), (uint8_t)(w >> 16), (uint8_t)(w >> 24) };
        wantpad("joystick right + 4-way hat down", &p, r, 4, -1, 1, R | D, 0x5);
    }

    /* the Fantech EOS Mini kind (a D-pad only pad), Android/D-input mode, both ways it may send it */
    {   /* (a) the D-pad as X/Y, 8 bits 0..255, centre 0x7f or 0x80; no hat; 12 buttons */
        static const uint8_t eos_axes[] = {
            0x05, 0x01, 0x09, 0x05, 0xa1, 0x01,
            0x15, 0x00, 0x26, 0xff, 0x00, 0x75, 0x08, 0x95, 0x02, 0x09, 0x30, 0x09, 0x31, 0x81, 0x02,
            0x05, 0x09, 0x19, 0x01, 0x29, 0x0c, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x0c, 0x81, 0x02,
            0x75, 0x04, 0x95, 0x01, 0x81, 0x03, 0xc0 };
        CHECK(hid_pad_parse(eos_axes, sizeof eos_axes, &p) && !p.hat.size && p.x.size == 8 && !p.x.sgn, "eos axes");
        wantpad("eos axes centred 7f/7f", &p, (const uint8_t[]){ 0x7f, 0x7f, 0, 0 }, 4, -1, 1, 0, 0);
        wantpad("eos axes centred 80/80", &p, (const uint8_t[]){ 0x80, 0x80, 0, 0 }, 4, -1, 1, 0, 0);
        wantpad("eos axes up-right, B", &p, (const uint8_t[]){ 0xff, 0x00, 0x02, 0 }, 4, -1, 1, U | R, 0x2);
        wantpad("eos axes down-left, Start (10)", &p, (const uint8_t[]){ 0x00, 0xff, 0x00, 0x02 }, 4, -1, 1, D | L, 0x200);
    }
    {   /* (b) the D-pad as a hat, dummy sticks X Y Z Rz held at 0x80; report ID 1 */
        static const uint8_t eos_hat[] = {
            0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x85, 0x01,
            0x09, 0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35, 0x15, 0x00, 0x26, 0xff, 0x00, 0x75, 0x08, 0x95, 0x04, 0x81, 0x02,
            0x09, 0x39, 0x15, 0x00, 0x25, 0x07, 0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
            0x75, 0x04, 0x95, 0x01, 0x81, 0x03,
            0x05, 0x09, 0x19, 0x01, 0x29, 0x0c, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x0c, 0x81, 0x02,
            0x75, 0x04, 0x95, 0x01, 0x81, 0x03, 0xc0 };
        CHECK(hid_pad_parse(eos_hat, sizeof eos_hat, &p) && p.hat.size == 4 && p.id == 1, "eos hat");
        wantpad("eos hat null, sticks centred", &p, (const uint8_t[]){ 1, 0x80, 0x80, 0x80, 0x80, 0x0f, 0x00, 0x00 }, 8, -1, 1, 0, 0);
        wantpad("eos hat up, A", &p, (const uint8_t[]){ 1, 0x80, 0x80, 0x80, 0x80, 0x00, 0x01, 0x00 }, 8, -1, 1, U, 0x1);
        wantpad("eos hat left", &p, (const uint8_t[]){ 1, 0x80, 0x80, 0x80, 0x80, 0x06, 0x00, 0x00 }, 8, -1, 1, L, 0);
    }

    CHECK(hid_pad_parse(combo, sizeof combo, &p) && p.id == 3 && p.nbtn == 8, "combo: id %d buttons %d", p.id, p.nbtn);
    wantpad("combo: the keyboard's report is not the pad's", &p, (const uint8_t[]){ 1, 0, 0, 4, 0, 0, 0, 0, 0 }, 9, -1, 0, 0, 0);
    wantpad("combo: pad report 3", &p, (const uint8_t[]){ 3, 0x81, 0x00, 0x7f }, 4, -1, 1, D, 0x81);
    CHECK(!hid_pad_parse(ds4, 20, &p), "ds4 cut short before the hat and buttons: taken");
}

int main(void)
{
    struct hid_mouse m;

    CHECK(hid_mouse_parse(plain, sizeof plain, &m), "plain: refused");
    CHECK(!m.ids && m.nbtn == 3 && m.btn.pos == 0 && m.x.pos == 8 && m.y.pos == 16 && m.wheel.pos == 24 &&
          m.x.size == 8 && m.wheel.size == 8 && !m.pan.size, "plain: layout");
    want("plain", &m, (const uint8_t[]){ 0x05, 0xfb, 0x10, 0x01 }, 4, 1, -5, 16, 1, 0, 5);
    want("plain, wheel down", &m, (const uint8_t[]){ 0x00, 0x00, 0x00, 0xff }, 4, 1, 0, 0, -1, 0, 0);
    want("plain, short report", &m, (const uint8_t[]){ 0x01, 0x02, 0x03 }, 3, 1, 2, 3, 0, 0, 1);

    CHECK(hid_mouse_parse(logi, sizeof logi, &m), "logi: refused");
    CHECK(m.ids && m.x.id == 2 && m.nbtn == 8 && m.x.pos == 16 && m.y.pos == 28 && m.x.size == 12 &&
          m.wheel.pos == 40 && m.pan.pos == 48, "logi: layout x %u/%u y %u wheel %u pan %u nbtn %u",
          m.x.pos, m.x.size, m.y.pos, m.wheel.pos, m.pan.pos, m.nbtn);
    /* x = -5 (0xffb), y = +300 (0x12c): bytes fb, cf, 12 */
    want("logi", &m, (const uint8_t[]){ 0x02, 0x13, 0x80, 0xfb, 0xcf, 0x12, 0xfe, 0x01 }, 8, 1, -5, 300, -2, 1, 0x13);
    want("logi, other report", &m, (const uint8_t[]){ 0x04, 0x13, 0x80, 0xfb, 0xcf, 0x12, 0xfe, 0x01 }, 8, 0, 0, 0, 0, 0, 0);

    CHECK(hid_mouse_parse(recv, sizeof recv, &m), "receiver: refused");
    CHECK(m.ids && m.x.id == 2 && m.btn.id == 2 && m.nbtn == 5 && m.x.pos == 16 && m.x.size == 16 &&
          m.y.pos == 32 && m.wheel.pos == 48, "receiver: layout x %u y %u wheel %u", m.x.pos, m.y.pos, m.wheel.pos);
    want("receiver, consumer key", &m, (const uint8_t[]){ 0x01, 0xe9, 0x00 }, 3, 0, 0, 0, 0, 0, 0);
    want("receiver, mouse", &m, (const uint8_t[]){ 0x02, 0x18, 0xaa, 0x00, 0xfc, 0x07, 0x00, 0x03 }, 8, 1, -1024, 7, 3, 0, 0x18);

    CHECK(!hid_mouse_parse(tablet, sizeof tablet, &m), "tablet: taken (absolute X/Y)");
    CHECK(!hid_mouse_parse(noxy, sizeof noxy, &m), "no X/Y: taken");
    CHECK(!hid_mouse_parse(plain, 20, &m), "cut short: taken");

    pads();
    printf(fails ? "hid_test FAILED (%d)\n" : "hid_test ALL OK\n", fails);
    return fails != 0;
}
